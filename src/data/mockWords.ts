// Helper to filter words by unit
export function getWordsForUnit(unit: OxfordUnit, allWords: VocabWord[]): VocabWord[] {
  const unitKey = unit.name.toLowerCase();
  const vnKey = unit.vietnameseName.toLowerCase();
  return allWords.filter(w => {
    if (w.unitId && w.unitId === unit.id) return true;
    const wordTopic = (w.topic || '').toLowerCase();
    return wordTopic.includes(unitKey) || wordTopic.includes(vnKey);
  });
}

// Helper to filter words by subtopic
export function getWordsForSubtopic(subtopic: OxfordSubtopic, unit: OxfordUnit, allWords: VocabWord[]): VocabWord[] {
  const subKey = subtopic.englishTitle.toLowerCase();
  const subVnKey = subtopic.vietnameseTitle.toLowerCase();
  
  return allWords.filter(w => {
    if (w.subtopicId && w.subtopicId === subtopic.id) return true;
    const wordSubtopic = (w.subtopic || '').toLowerCase();
    if (wordSubtopic && (wordSubtopic.includes(subKey) || wordSubtopic.includes(subVnKey))) return true;

    // Fallback: check if word belongs to this unit and topic text matches
    const wordTopic = (w.topic || '').toLowerCase();
    if (wordTopic.includes(subKey) || wordTopic.includes(subVnKey)) return true;

    return false;
  });
}

